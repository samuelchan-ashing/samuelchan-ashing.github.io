"""Writes assets/js/sim-code.js: the Python files of tools/covers, shown on the paper pages ("View the simulation code").
Run after editing any of them:  python3 tools/covers/build_code_js.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
FILES = {   # key used in assets/js/data.js (field "code") -> script
    "dyson-laguerre": "dyson_laguerre.py",
    "dyson-jacobi": "dyson_jacobi.py",
    "metastable": "metastable.py",
    "ornstein-uhlenbeck": "ornstein_uhlenbeck.py",
}
data = {k: {"file": f, "code": open(os.path.join(HERE, f), encoding="utf-8").read()} for k, f in FILES.items()}
out = os.path.join(HERE, "..", "..", "assets", "js", "sim-code.js")
open(out, "w", encoding="utf-8").write(
    "/* Generated by tools/covers/build_code_js.py from tools/covers/*.py: the code behind each cover. */\n"
    "window.SIM_CODE = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print("wrote", os.path.normpath(out))
