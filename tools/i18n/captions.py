if __name__ == "__main__":                      # write the captions into data.js, fr.py and kr.py (idempotent)
    import json, os, re
    here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..", "..")
    p = os.path.join(root, "assets", "js", "data.js"); t = open(p, encoding="utf-8").read()
    t = re.sub(r"\n[ \t]*caption: .*", "", t)
    for code, html in EN.items():
        mm = re.search(r'\n(\s*)code: "' + re.escape(code) + r'",[^\n]*', t)
        t = t[:mm.end()] + f'\n{mm.group(1)}caption: {json.dumps(html, ensure_ascii=False)},   // under the cover (tools/i18n/captions.py)' + t[mm.end():]
    open(p, "w", encoding="utf-8").write(t)
    MARK = " # ---------- captions under the paper covers (generated by captions.py)\n"
    for fn, D in [("fr.py", FR), ("kr.py", KR)]:
        fn = os.path.join(here, fn); x = open(fn, encoding="utf-8").read()
        x = re.sub(r"\n # ---------- captions under the paper covers.*?(?=\n}\s*$)", "", x, flags=re.S)
        block = "\n" + MARK + "".join(f' "#cap-{c}": {json.dumps(h, ensure_ascii=False)},\n' for c, h in D.items())
        i = x.rstrip().rfind("}"); x = x[:i].rstrip() + "\n" + block.rstrip("\n") + "\n" + x[i:]
        open(fn, "w", encoding="utf-8").write(x)
    print("captions written to data.js, fr.py, kr.py")
