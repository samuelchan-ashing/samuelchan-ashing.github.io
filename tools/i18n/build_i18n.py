# Builds assets/js/i18n.js from fr.py (French) and kr.py (Reunion Creole).
import json, os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from fr import FR
from kr import KR
NB = "\u00a0"
fr = {}
for k, v in FR.items():
    if not k.startswith("#"):
        v = re.sub(r" ([:;?!])(?=\s|$)", NB + r"\1", v)   # French spacing before : ; ? !
    fr[k] = v
kr = dict(KR)
missing = [k for k in fr if k not in kr]
if missing:
    print("not yet in kr.py (stay in English in Creole):", missing)
ENGINE = r'''
  const root = document.documentElement;
  const baseLang = root.getAttribute("lang") || "en";       // agregation.html is written in French
  const DICTS = { fr: FR, rcf: KR };                         // rcf = Reunion Creole (ISO 639-3)
  let lang = "en";                                           // English is always the default
  try { const s = localStorage.getItem("lang"); if (DICTS[s]) lang = s; } catch (e) { /* storage unavailable */ }
  const MONTHS_RCF = ["zanvié", "févrié", "mars", "avril", "mé", "zin", "zwiyé", "out", "septanm", "oktob", "novanm", "désanm"];

  // what is never translated: scripts, maths, the arXiv text and its keywords, memoir section titles
  const SKIP = "script, style, svg, math, .paper, #keywords, .tracks, [data-i18n], [data-no-i18n]";
  const ATTRS = ["aria-label", "alt"];
  const textOrig = new WeakMap(), htmlOrig = new WeakMap(), attrOrig = new WeakMap();
  const dict = () => DICTS[lang] || null;
  const has = (k) => { const d = dict(); return !!d && Object.prototype.hasOwnProperty.call(d, k); };
  const norm = (s) => s.replace(/\s+/g, " ").trim();

  function t(en, vars) {
    let s = has(en) ? dict()[en] : en;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
    return s;
  }

  function translate(scope) {
    scope = scope || document.body;
    const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        const p = n.parentElement;
        if (!p || p.closest(SKIP)) return NodeFilter.FILTER_REJECT;
        return /[A-Za-zÀ-ÿ]/.test(n.nodeValue) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    const nodes = [];
    for (let n; (n = walker.nextNode());) nodes.push(n);
    for (const n of nodes) {
      const en = textOrig.has(n) ? textOrig.get(n) : n.nodeValue;
      const key = norm(en);
      if (has(key)) {
        if (!textOrig.has(n)) textOrig.set(n, en);
        n.nodeValue = en.match(/^\s*/)[0] + dict()[key] + en.match(/\s*$/)[0];
      } else if (textOrig.has(n)) {
        n.nodeValue = textOrig.get(n);
      }
    }
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      if (!htmlOrig.has(el)) htmlOrig.set(el, el.innerHTML);
      const k = "#" + el.dataset.i18n;
      el.innerHTML = has(k) ? dict()[k] : htmlOrig.get(el);
    });
    scope.querySelectorAll(ATTRS.map((a) => "[" + a + "]").join(",")).forEach((el) => {
      if (el.closest(".paper")) return;
      let o = attrOrig.get(el);
      if (!o) { o = {}; ATTRS.forEach((a) => { if (el.hasAttribute(a)) o[a] = el.getAttribute(a); }); attrOrig.set(el, o); }
      for (const a in o) el.setAttribute(a, has(norm(o[a])) ? dict()[norm(o[a])] : o[a]);
    });
  }

  let titleOrig = null;
  function apply() {
    if (titleOrig === null) titleOrig = document.title;
    translate(document.body);
    document.title = t(norm(titleOrig));
    root.setAttribute("lang", lang === "en" ? baseLang : lang);
    root.classList.remove("i18n-pending");
    document.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
  }

  window.I18N = {
    t, apply, translate,
    get lang() { return lang; },
    languages: ["en", "fr", "rcf"],
    set(l) {
      lang = DICTS[l] ? l : "en";
      try { localStorage.setItem("lang", lang); } catch (e) { /* the choice just isn't remembered */ }
      apply();
    },
    date(d, opts) {
      const x = new Date(d + "T12:00:00");
      if (lang === "rcf") return x.getDate() + " " + MONTHS_RCF[x.getMonth()] + " " + x.getFullYear();
      return x.toLocaleDateString(lang === "fr" ? "fr-FR" : "en-GB", opts || { day: "numeric", month: "long", year: "numeric" });
    }
  };
'''
js = ('/* Translations of the site.\n'
      '   The pages are written in English; this file holds the French and the Reunion Creole (kréol reyoné).\n'
      '   Keys are the English text exactly as it appears on the page (spaces collapsed); "#id" keys replace the whole\n'
      '   content of an element with data-i18n="id". Generated by tools/i18n/build_i18n.py from fr.py and kr.py.\n'
      '   English is always the default; a visitor\'s choice (language menu next to the dark-mode button) is remembered. */\n'
      '(function () {\n  "use strict";\n'
      '  const FR = ' + json.dumps(fr, ensure_ascii=False, indent=1).replace("\n", "\n  ") + ';\n'
      '  const KR = ' + json.dumps(kr, ensure_ascii=False, indent=1).replace("\n", "\n  ") + ';\n' + ENGINE + '})();\n')
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "assets", "js", "i18n.js")
open(out, "w", encoding="utf-8").write(js)
print("wrote", out, len(fr), "French and", len(kr), "Creole entries")
